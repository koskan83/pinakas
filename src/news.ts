/** Έκδοση (ημερομηνία του build) και τα νέα της, για το «Τι νέο» μετά από ενημέρωση. */

declare const __BUILD__: string;

export const VERSION: string = typeof __BUILD__ === 'string' ? __BUILD__ : 'δοκιμαστική';

/** Αλλάζει κάθε φορά που αλλάζει η λίστα: τότε το «Τι νέο» εμφανίζεται μία φορά σε κάθε συσκευή. */
export const NEWS_ID = '2026-10-13';

export const NEWS: string[] = [
  'Δημοτικό: τα εργαλεία (κλάσματα, κυβάκια, κρεμάλα, ζυγαριά…) δουλεύουν με πάτημα ό,τι εργαλείο κι αν κρατάς.',
  'Μεγάλα παράθυρα για ονόματα και επιβεβαιώσεις· η λέξη της κρεμάλας γράφεται με κουκκίδες.',
  'Μενού ☰ σε τρεις ομάδες: Μάθημα, Σελίδα, Εφαρμογή.',
  'Ονόματα κάτω από τα κουμπιά των αξόνων (Κλίμακα, Εμβαδόν, Όριο…).',
  'Έτοιμες σελίδες: Μελέτη συνάρτησης, Κλάσματα, Αριθμοί ως το 1000 και άλλες, από το ＋ της σελίδας.',
];

const KEY = 'grafida.news';

/** true αν η συσκευή έχει ξαναχρησιμοποιήσει την εφαρμογή και δεν έχει δει αυτά τα νέα. Τα σημειώνει ως διαβασμένα. */
export function newsPending(returning: boolean): boolean {
  try {
    const seen = localStorage.getItem(KEY);
    localStorage.setItem(KEY, NEWS_ID);
    return returning && seen !== NEWS_ID;
  } catch {
    return false;
  }
}
